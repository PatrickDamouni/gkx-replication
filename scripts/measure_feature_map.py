"""Validate the reviewed map (config/feature_map.csv) against GKX datashare — D024.

Measures, never selects. For each OSAP-mapped characteristic on 25 sample months
(1960-2016, pre-2017 files only): mean within-month Spearman ρ between datashare and the
mapped OSAP value (sign restored, transform and declared shift applied), coverage of
datashare's non-missing rows, and distinct values. Status by D024:
  validated: ρ ≥ 0.80, coverage ≥ 70%, and ≥ 5 distinct values unless the GKX char is binary
  proxy:     0.60 ≤ ρ < 0.80 with the same coverage/distinct conditions
  missing:   otherwise, or no counterpart in the map
CRSP rebuilds take their status from results/crsp_chars_validation.md (exact rebuilds).

Usage: uv run python scripts/measure_feature_map.py   (writes results/feature_map_measured.{csv,md})
"""

from pathlib import Path

import pandas as pd

from gkx.feature_map import _add_months, apply_osap, load_map, osap_signs

DS = "data/raw/datashare_pre2017.parquet"
OSAP = "data/raw/osap_firm_char_202510_pre2017.parquet"
MONTHS = [int(f"{y}06") for y in range(1960, 2017, 2)][:24] + [201612]
VALID, PROXY, COVERAGE, DISTINCT = 0.80, 0.60, 0.70, 5


def _measure(both: pd.DataFrame, g: str) -> dict:
    a, b = both[g], both[f"{g}__osap"]
    ok = a.notna() & b.notna()
    coverage = ok.sum() / a.notna().sum()
    rho = (
        both[ok]
        .groupby("yyyymm")
        .apply(lambda m: m[g].rank().corr(m[f"{g}__osap"].rank()), include_groups=False)
        .mean()
    )
    distinct = int(b[ok].nunique())
    binary_gkx = a.dropna().nunique() <= 2
    shape_ok = coverage >= COVERAGE and (binary_gkx or distinct >= DISTINCT)
    if shape_ok and rho >= VALID:
        status = "validated"
    elif shape_ok and rho >= PROXY:
        status = "proxy"
    else:
        status = "missing (failed validation)"
    return {
        "rho": round(rho, 3),
        "coverage": round(coverage, 3),
        "distinct": distinct,
        "status": status,
    }


def main() -> None:
    fmap = load_map()
    osap_rows = fmap[fmap["source"] == "osap"]
    needed = sorted(set(MONTHS) | {int(m) for m in _add_months(pd.Series(MONTHS), -4)})
    osap = pd.read_parquet(
        OSAP,
        columns=["permno", "yyyymm", *osap_rows["signal"].unique()],
        filters=[("yyyymm", "in", needed)],
    )
    mapped = apply_osap(osap, fmap, osap_signs())
    ds = pd.read_parquet(
        DS, columns=["permno", "yyyymm", *osap_rows["gkx"]], filters=[("yyyymm", "in", MONTHS)]
    )
    both = ds.merge(mapped, on=["permno", "yyyymm"], how="left", suffixes=("", "__osap"))

    rows = []
    for _, r in fmap.iterrows():
        base = {"gkx": r["gkx"], "source": r["source"], "signal": r["signal"]}
        if r["source"] == "crsp":
            rows.append(base | {"status": "validated (exact CRSP rebuild)"})
        elif r["source"] == "none":
            rows.append(base | {"status": "missing (no counterpart)"})
        else:
            rows.append(base | _measure(both, r["gkx"]))

    table = pd.DataFrame(rows)
    table.to_csv("results/feature_map_measured.csv", index=False)
    counts = table["status"].str.split(" ").str[0].value_counts().to_dict()
    Path("results/feature_map_measured.md").write_text(
        "# Characteristic map: validation evidence (D024)\n\n"
        "Generated by `scripts/measure_feature_map.py` from the reviewed `config/feature_map.csv`. "
        f"Mean within-month Spearman over {len(MONTHS)} months ({MONTHS[0]}..{MONTHS[-1]}); "
        f"validated ρ ≥ {VALID}, proxy ρ ≥ {PROXY}; coverage ≥ {COVERAGE:.0%}; ≥ {DISTINCT} "
        "distinct values unless the GKX characteristic is binary.\n\n"
        f"**Counts:** {counts}\n\n" + table.to_markdown(index=False) + "\n"
    )
    print(table.to_string(index=False))
    print(counts)


if __name__ == "__main__":
    main()
